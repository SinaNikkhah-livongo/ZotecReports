         NOW() AS created_at,
         '0' AS created_by,
         NOW() AS updated_at,
         '0' AS updated_by,
         accountmrnid,
         primarymrnid,
         memberid,
         patientphone,
         patientemail,
         practice
             ,(SELECT organization_id
               FROM teladoc_eds.billings b
                        JOIN teladoc_eds.group_billing_relations gbr ON gbr.billing_id = b.billing_id
               WHERE gbr.group_id = cpl.groupid
                 AND gbr.exclusion_cd = 'IN'
                 AND b.exclusion_cd = 'IN'
               LIMIT 1 ) AS billingorgid

     FROM
         claim.claim_process_log cpl
     WHERE business_date BETWEEN @business_start_ts AND @business_end_ts
       AND servicedt BETWEEN @service_start_dt AND @service_end_dt )z
WHERE billingorgid IS NOT NULL
ORDER BY consultid, servicedt;
