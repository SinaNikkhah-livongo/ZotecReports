    AccountType,
    PrimaryLastName,
    PrimaryFirstName,
    PrimaryMiddleName,
    PrimaryDob,
    PrimaryGender,
    SourceHealthPlanId,
    PrimarySourceHealthPlanId,
    PatientLastName,
    PatientFirstName,
    PatientMiddleName,
    PatientDob,
    PatientGender,
    MailAddress1,
    MailAddress2,
    MailCity,
    MailState,
    MailZip,
    DiagnosisCode,
    ServiceDt,
    CptCode,
    `Modifier`,
    PlaceOfService,
    CompanyPaidAmount,
    MemberPaidAmount,
    TotalAmount,
    PayerName,
    PayerCD,
    PayerId,
    RenderingProviderId,
    RenderingProviderFirstName,
    RenderingProviderMiddleName,
    RenderingProviderLastName,
