         mailaddress2,
         mailcity,
         mailstate,
         mailzip,
         teladoc_eds.`f_aes_decryption_serial_iv`(encrypt_diagnosiscode,NULL,'SQL','N','claim_process_log','encrypt_diagnosiscode') AS diagnosiscode,
         servicedt,
         teladoc_eds.`f_aes_decryption_serial_iv`(encrypt_cptcode,NULL,'SQL','N','claim_process_log','encrypt_cptcode') AS cptcode,
         `Modifier`,
         placeofservice,
         companypaidamount,
